# Generates the R-side ground truth for the spml <-> GWmodel GWPCA parity
# test (spml/tests/test_decomposition.py::test_gwpca_matches_r_gwmodel_reference).
#
# Not run by CI or pytest - this is a one-off script, run once inside a
# throwaway environment with R + GWmodel installed, e.g.:
#
#   mamba create -n r-gwmodel-ref -c defaults r-base r-gwmodel -y
#   mamba run -n r-gwmodel-ref Rscript generate_gwpca_reference.R
#
# Recorded package version at generation time: GWmodel 2.3.1 (R 4.3.3).
#
# Important: the actual installed gwpca() has NO scale.vars/scaling argument
# (older docs/snippets describing one refer to a different/older function).
# The local decomposition always runs on the raw `x` it is given; a user who
# wants standardized GWPCA manually calls scale() before calling gwpca(),
# per the package's own \dontrun{} example. That manual-pre-scale workflow is
# exactly what spml's `standardize=True` reproduces (global z-score once,
# then local weighted covariance) - see spml/decomposition.py's module
# docstring. We replicate that workflow here for the "std" case rather than
# passing a (nonexistent) function argument.
#
# gwpca()'s returned `gwpca.scores` also carries no row-identity metadata
# (rownames are NULL), so neighbour identity for each location is
# reconstructed here directly via gw.dist()/gw.weight() - the same functions
# gwpca() uses internally to build each neighbourhood.
#
# Reads gwpca_reference_input.csv (checked in, generated by a matching Python
# script using the same rng-seeded logic as the `toy_data` pytest fixture)
# and writes the checked-in reference CSVs read by the pytest test - the test
# itself never needs R installed.
#
# Kernel/bandwidth: boxcar (unambiguous 0/1 weight, sidesteps any formula
# difference between libpysal's and GWmodel's smooth kernels), fixed
# (distance) bandwidth = 3.5, chosen so every one of the 60 fixture points
# has a neighbourhood of at least 6 points (GWmodel silently skips any
# location with <=5) - verified: neighbourhood sizes range 6-30 at this
# bandwidth. spml's `standardize=True` now deliberately replicates GWmodel's
# shared-last-location eigenvalue-normalization behaviour too (see
# decomposition.py's "Deliberate parity with GWmodel::gwpca" note), so
# eigenvalues and scores are directly comparable here, not just loadings/PTV.

suppressMessages(library(GWmodel))
suppressMessages(library(sp))

bw <- 3.5
vars <- c("a", "b", "c", "d")
k <- length(vars)

input <- read.csv("gwpca_reference_input.csv")
coords <- as.matrix(input[, c("x", "y")])
n <- nrow(input)

write_case <- function(standardize, suffix) {
  x_mat <- as.matrix(input[, vars])
  if (standardize) {
    # Population sd (divide by n), matching spml's `_standardize` exactly -
    # NOT R's `scale()` default (sample sd, divide by n-1).
    mu <- colMeans(x_mat)
    pop_sd <- sqrt(colSums(sweep(x_mat, 2, mu) ^ 2) / nrow(x_mat))
    x_mat <- sweep(sweep(x_mat, 2, mu), 2, pop_sd, "/")
  }
  data_sp <- SpatialPointsDataFrame(coords, as.data.frame(x_mat))

  res <- gwpca(
    data_sp,
    vars = vars,
    bw = bw,
    kernel = "boxcar",
    adaptive = FALSE,
    k = k,
    scores = TRUE,
    cv = FALSE
  )

  # --- eigenvalues (res$var), already GWmodel-faithful shared-divisor ---
  eig <- as.data.frame(res$var)
  colnames(eig) <- paste0("PC", seq_len(k))
  eig$location <- seq_len(n) - 1L
  write.csv(
    eig[, c("location", paste0("PC", seq_len(k)))],
    sprintf("gwpca_reference_eigenvalues_%s.csv", suffix),
    row.names = FALSE
  )

  # --- loadings (res$loadings, dim n x p x k) -> long format ---
  loadings_rows <- vector("list", n * k)
  idx <- 1
  for (i in seq_len(n)) {
    for (comp in seq_len(k)) {
      loadings_rows[[idx]] <- c(
        location = i - 1L,
        component = comp,
        setNames(as.list(res$loadings[i, , comp]), vars)
      )
      idx <- idx + 1
    }
  }
  write.csv(
    do.call(rbind.data.frame, loadings_rows),
    sprintf("gwpca_reference_loadings_%s.csv", suffix),
    row.names = FALSE
  )

  # --- scores (res$gwpca.scores[[i]]: matrix, rows=neighbours, no rownames)
  # Reconstruct neighbour identity the same way gwpca() builds it internally.
  dp.locat <- coords
  score_rows <- list()
  ridx <- 1
  for (i in seq_len(n)) {
    dist.vi <- gw.dist(dp.locat, focus = i)
    wt <- gw.weight(dist.vi, bw, "boxcar", FALSE)
    neighbor_idx <- which(wt > 0) - 1L  # 0-based, to match Python
    mat <- res$gwpca.scores[[i]]
    stopifnot(nrow(mat) == length(neighbor_idx))
    for (r in seq_along(neighbor_idx)) {
      score_rows[[ridx]] <- c(
        location = i - 1L,
        neighbor = neighbor_idx[r],
        setNames(as.list(mat[r, ]), paste0("PC", seq_len(k)))
      )
      ridx <- ridx + 1
    }
  }
  write.csv(
    do.call(rbind.data.frame, score_rows),
    sprintf("gwpca_reference_scores_%s.csv", suffix),
    row.names = FALSE
  )

  invisible(res)
}

write_case(FALSE, "cov")
write_case(TRUE, "std")

cat("done\n")
